"""
Loss coverage matrix: for every junction type of the shipped libraries, the
loss function it uses and its flow-dependent variants, as a Markdown table.

    python3 tools/loss_coverage.py           # print the matrix
    python3 tools/loss_coverage.py --write   # also rewrite it in freecad/HVAC/libraries/README.md

The README section sits between the two LOSS-COVERAGE markers below;
tests/test_loss_coverage.py fails when it is out of date, so run this
with --write after changing a type-def's loss.
"""

import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(REPO_ROOT, "freecad", "HVAC", "libraries", "README.md")
LIBRARY_IDS = ("builtin_basic", "smacna")
BEGIN = "<!-- LOSS-COVERAGE:BEGIN (generated by tools/loss_coverage.py, do not edit by hand) -->"
END = "<!-- LOSS-COVERAGE:END -->"


def _variant_text(variant):
    """One loss variant as 'when ... -> function'."""
    parts = []
    constraints = variant.constraints or {}
    for key, rule in sorted(constraints.items()):
        if key == "qualifiers":
            for q_key, q_rule in sorted((rule or {}).items()):
                parts.append("{} {}".format(q_key, "/".join(q_rule.get("enum", []))))
        elif isinstance(rule, dict) and "enum" in rule:
            parts.append("/".join(rule["enum"]))
        else:
            parts.append(key)
    return "{}: `{}`".format(", ".join(parts) or "always", variant.function)


def coverage_rows(registry):
    """(library id, type id, profiles, kind, loss text) for every junction type, in a stable order."""
    rows = []
    for library_id in LIBRARY_IDS:
        library = registry.get_library(library_id)
        for type_def in sorted(library.list_types(), key=lambda t: t.id):
            if type_def.category != "junction":
                continue
            kind = type_def.selection.kind
            if type_def.loss_function or type_def.loss_variants:
                text = "`{}`".format(type_def.loss_function) if type_def.loss_function else "(none)"
                if type_def.loss_variants:
                    text += "; " + "; ".join(_variant_text(v) for v in type_def.loss_variants)
            elif kind == "placeholder":
                text = "none (marker)"
            elif type_def.flow_boundary == "Closed" and type_def.flow_boundary_locked:
                text = "none (no flow: always closed)"
            else:
                text = "**MISSING**"
            profiles = ", ".join(type_def.profiles) or "Generic"
            rows.append((library_id, type_def.id, profiles, kind, text))
    return rows


def coverage_markdown(registry):
    lines = [
        "| Library | Type | Profiles | Selection | Loss (default; flow-dependent variants) |",
        "|---|---|---|---|---|",
    ]
    for library_id, type_id, profiles, kind, text in coverage_rows(registry):
        lines.append("| {} | `{}` | {} | {} | {} |".format(library_id, type_id, profiles, kind, text))
    return "\n".join(lines)


def load_registry():
    if REPO_ROOT not in sys.path:
        sys.path.insert(0, REPO_ROOT)
    from freecad.HVAC.library.Library import HVACLibraryRegistry

    registry = HVACLibraryRegistry()
    registry.set_search_paths([os.path.join(REPO_ROOT, "freecad", "HVAC", "libraries")])
    registry.ensure_loaded()
    return registry


def readme_section(text):
    """The current matrix in the README text (between the markers), or None if the markers are missing."""
    if BEGIN not in text or END not in text:
        return None
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip()


def write_readme(markdown):
    with open(README, encoding="utf-8") as f:
        text = f.read()
    if readme_section(text) is None:
        raise SystemExit("README has no LOSS-COVERAGE markers")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    with open(README, "w", encoding="utf-8", newline="\n") as f:
        f.write(head + BEGIN + "\n\n" + markdown + "\n\n" + END + tail)


if __name__ == "__main__":
    # Outside FreeCAD the library code needs the same stubs the unit tests install.
    sys.path.insert(0, REPO_ROOT)
    sys.path.insert(0, os.path.join(REPO_ROOT, "tests"))
    import conftest  # noqa: F401

    table = coverage_markdown(load_registry())
    print(table)
    if "--write" in sys.argv:
        write_readme(table)
        print("README updated")
